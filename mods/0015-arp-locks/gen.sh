#!/bin/sh
# Regenerate stub.s from arpl.c + hook.s (needs an m68k gcc; the build itself only
# assembles stub.s). Read-only data (tables, strings) goes to section .s7.
set -e
cd "$(dirname "$0")"
CC=${CC:-m68k-elf-gcc}
$CC -mcpu=5475 -msoft-float -std=gnu99 -Os -ffreestanding -fno-builtin -fomit-frame-pointer \
    -fno-asynchronous-unwind-tables -fno-ident -fno-common -ffunction-sections -fdata-sections -Wall -Wextra -S arpl.c -o arpl.gen.s
{
  echo "| 0015-arp-locks - GENERATED by gen.sh from arpl.c and hook.s; edit those, not this."
  echo
  cat hook.s
  echo
  grep -v "^#NO_APP" arpl.gen.s | sed -E 's/\.section\t\.text\.([^,]*)/.section\t.c_\1/; s/\.section\t\.rodata\.([^,]*)/.section\t.r_\1/; s/\.section\t\.rodata(,|$)/.section\t.r_misc\1/; s/^\t\.section\t\.rodata$/\t.section\t.r_misc,"a",@progbits/'
} | sed -E 's/^\t\.section\t\.r_misc$/\t.section\t.r_misc,"a",@progbits/' > stub.s
rm -f arpl.gen.s
